"""基于河北东方学院开题报告模板生成正式开题报告 docx。

模板结构：表0（题目/学院/专业/班级/姓名/学号/指导教师/开题时间 8 行）
表1：r0 = 正文大单元格（四节+参考文献），r1 = 指导教师意见，r2 = 审核小组意见。
格式：正文宋体小四（12pt）、西文 Times New Roman、1.5 倍行距、首行缩进 2 字符；
节标题加粗不缩进。
"""
import copy
import docx
from docx.shared import Pt
from docx.oxml.ns import qn

TPL = r"C:\Users\许\AppData\Local\Temp\thesis_tpl\开题报告_template.docx"
OUT = r"e:\code\resumatch-ai\docs\开题\河北东方学院本科毕业论文（设计）开题报告.docx"

TITLE = "基于大模型的智能简历诊断与岗位匹配推荐系统的设计与实现"

d = docx.Document(TPL)

# ---------- 表0：填题目 ----------
info = d.tables[0]
for row in info.rows:
    texts = [c.text.strip() for c in row.cells]
    if any("题目" in t for t in texts):
        val = row.cells[-1]
        for p in list(val.paragraphs):
            p._element.getparent().remove(p._element)
        p = val.add_paragraph()
        run = p.add_run(TITLE)
        run.font.size = Pt(10.5)  # 五号：24 字题目在单元格内一行放下
        run.font.name = "Times New Roman"
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
        run.font.bold = True
        break

# ---------- 表1 r0：写正文 ----------
cell = d.tables[1].rows[0].cells[0]
# 清掉模板说明段落
for p in list(cell.paragraphs):
    p._element.getparent().remove(p._element)


def set_font(run, size=12, bold=False, east="宋体"):
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), east)


def para(text, indent=True, bold=False, align=None):
    p = cell.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.space_before = Pt(0)
    pf.space_after = Pt(0)
    if indent:
        pf.first_line_indent = Pt(24)
    if align:
        p.alignment = align
    r = p.add_run(text)
    set_font(r, 12, bold)
    return p


